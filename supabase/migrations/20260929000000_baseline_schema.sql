-- Triggers ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['photo_events', 'photo_athletes', 'photo_matches', 'photo_bookings', 'photo_orders'] loop
    execute format('drop trigger if exists %I on public.%I', t || '_set_updated_at', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.photo_set_updated_at()', t || '_set_updated_at', t);
  end loop;
end $$;

-- Row Level Security -----------------------------------------------------------
-- Owner-only policies for every table. The helper creates the four standard
-- policies when missing, so re-running never duplicates them.
create or replace function public.photo_ensure_owner_policies(p_table text)
returns void language plpgsql as $$
begin
  execute format('alter table public.%I enable row level security', p_table);
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = p_table and policyname = p_table || '_owner_select') then
    execute format('create policy %I on public.%I for select using ((select auth.uid()) = owner_id)', p_table || '_owner_select', p_table);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = p_table and policyname = p_table || '_owner_insert') then
    execute format('create policy %I on public.%I for insert with check ((select auth.uid()) = owner_id)', p_table || '_owner_insert', p_table);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = p_table and policyname = p_table || '_owner_update') then
    execute format('create policy %I on public.%I for update using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id)', p_table || '_owner_update', p_table);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = p_table and policyname = p_table || '_owner_delete') then
    execute format('create policy %I on public.%I for delete using ((select auth.uid()) = owner_id)', p_table || '_owner_delete', p_table);
  end if;
end $$;

