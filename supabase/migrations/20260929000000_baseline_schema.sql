-- =============================================================================
-- Blue Belt Media — Tournament Watcher: canonical baseline schema
-- =============================================================================
-- Reproduces, from a clean Supabase project, every table the app touches with
-- its foreign keys, constraints, indexes, RLS policies and triggers. Every
-- statement is idempotent so this file can also be applied on top of an
-- existing project (it was written against the live schema on 2026-10-02).
--
-- Isolation model: every row carries owner_id = auth.uid() and every policy
-- is "(select auth.uid()) = owner_id". Nothing here widens that.
-- =============================================================================

create extension if not exists pgcrypto;

-- updated_at maintenance -------------------------------------------------------
create or replace function public.photo_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- photo_events -----------------------------------------------------------------
create table if not exists public.photo_events (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  venue text,
  country text,
  event_date date,
  platform text not null,
  source_url text,
  timezone text not null default 'Asia/Qatar',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint photo_events_platform_check check (platform = any (array['AJP'::text, 'SMOOTHCOMP'::text, 'OTHER'::text]))
);
alter table public.photo_events add column if not exists country text;
create index if not exists photo_events_owner_idx on public.photo_events (owner_id);

