-- Payment events are written by the server (service role) and only read by owners.
alter table public.photo_payment_events enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'photo_payment_events' and policyname = 'photo_payment_events_owner_select') then
    create policy photo_payment_events_owner_select on public.photo_payment_events for select using ((select auth.uid()) = owner_id);
  end if;
end $$;
